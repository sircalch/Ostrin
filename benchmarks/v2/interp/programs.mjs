export function expectedText(program, K) {
  if (program.kind === "float") {
    const value = program.expectedFloat(K);
    return { kind: "float", value };
  }
  return { kind: "int", value: program.expected(K).toString() };
}

export function renderManifest() {
  return JSON.stringify(
    PROGRAMS.map((p) => ({ name: p.name, group: p.group, kind: p.kind, file: `programs/${p.name}.ostrin` })),
    null,
    2,
  ) + "\n";
}

function main() {
  const mode = process.argv[2];
  if (mode === "--write") {
    mkdirSync(outDir, { recursive: true });
    for (const p of PROGRAMS) writeFileSync(join(outDir, `${p.name}.ostrin`), p.source, "utf8");
    writeFileSync(join(here, "manifest.json"), renderManifest(), "utf8");
    console.log(`interp programs: wrote ${PROGRAMS.length} programs`);
    return;
  }
  if (mode === "--check") {
    let stale = 0;
    for (const p of PROGRAMS) {
      const file = join(outDir, `${p.name}.ostrin`);
      if (!existsSync(file) || readFileSync(file, "utf8") !== p.source) stale += 1;
    }
    if (stale > 0 || readFileSync(join(here, "manifest.json"), "utf8") !== renderManifest()) {
      console.error(`interp programs: ${stale} stale file(s); run with --write`);
      process.exitCode = 1;
    } else console.log("interp programs: current");
    return;
  }
  console.log(PROGRAMS.map((p) => p.name).join("\n"));
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1].replace(/\\/g, "/")}`).href) main();

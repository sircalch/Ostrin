// Interpreter workloads for the Benchmark V2 interpreter extension. Each program takes K, the number of repetitions of
// its workload, as its first argument (`ostrinc --run file -- K`), and prints one line `RESULT <name> <value>`.
//
// Usage: node benchmarks/v2/interp/programs.mjs --write   (writes benchmarks/v2/interp/programs/*.ostrin and manifest.json)
//        node benchmarks/v2/interp/programs.mjs --check   (verifies that the committed files are current)
//
// Every program has an exact or tolerance reference computed here, independently of Ostrin (BigInt for integers,
// the same IEEE double operations for floats). The references are checked against every run before any timing is
// used. Programs that have no independent reference (none at present) would be marked as cross-version only.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "programs");

const N = 500000; // iterations per repetition of a micro loop
const NN = 600; // outer size of the nested loops (NN * NN inner iterations)

const header = (name, prelude = "") => `// Benchmark V2 interpreter workload: ${name}. Generated by benchmarks/v2/interp/programs.mjs; do not edit.
${prelude}fn main() -> Void {
    values = args()
    mut repeats = 1
    if values.length() > 0 {
        repeats = parse_int(values[0]).unwrap()
    }
`;

function loop(body) {
  return `    mut total = 0
    for k in 0 until repeats {
${body}
    }
`;
}

function frameBody(count, label) {
  // `count` names defined in the body of each iteration, then a use of the first and the last
  let lines = "";
  for (let j = 0; j < count; j += 1) lines += `            a${j} = i + ${j}\n`;
  lines += `            total = total + a0 + a${count - 1}\n`;
  return { lines, label };
}

const frameSmallBody = `            a = i + 1
            b = a * 2
            c = b + a
            total = total + c
`;


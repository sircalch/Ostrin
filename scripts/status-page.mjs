#!/usr/bin/env node

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const scorecardPath = path.join(repositoryRoot, "validation", "quality-scorecard.json");
const outputPath = path.join(repositoryRoot, "website", "status-data.js");

export function renderStatusData(scorecard) {
  return `// Generated by scripts/status-page.mjs. Do not edit by hand.\n` +
    `globalThis.OSTRIN_STATUS = Object.freeze(${JSON.stringify(scorecard, null, 2)});\n`;
}

export function buildStatusData(root = repositoryRoot) {
  const source = path.join(root, "validation", "quality-scorecard.json");
  if (!existsSync(source)) throw new Error("validation/quality-scorecard.json is missing; run node scripts/quality-scorecard.mjs --write");
  return JSON.parse(readFileSync(source, "utf8"));
}

function main() {
  const expected = renderStatusData(buildStatusData());
  if (process.argv.includes("--write")) {
    writeFileSync(outputPath, expected, "utf8");
    console.log("status-page: wrote website/status-data.js");
  } else if (!existsSync(outputPath) || readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n") !== expected) {
    console.error("status-page: website/status-data.js is stale; run node scripts/status-page.mjs --write");
    process.exitCode = 1;
  } else {
    console.log("status-page: ok");
  }
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();

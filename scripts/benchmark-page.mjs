import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const inputPath = path.join(repositoryRoot, "target", "benchmarks", "benchmark.json");
const outputPath = path.join(repositoryRoot, "website", "benchmark-data.js");

if (!existsSync(inputPath)) {
  throw new Error("target/benchmarks/benchmark.json is missing; run scripts/benchmark.mjs first");
}

const report = JSON.parse(readFileSync(inputPath, "utf8"));
if (report.schema !== 2 || !Array.isArray(report.workloads) || report.workloads.length === 0) {
  throw new Error("benchmark.json: expected schema 2 with at least one workload");
}

const finite = (value, label) => {
  if (!Number.isFinite(value)) throw new Error(`benchmark.json: ${label} is not finite`);
  return value;
};

const data = {
  schema: 1,
  commit: String(report.commit ?? "unknown"),
  compiler: String(report.compilerVersion ?? "unknown"),
  node: String(report.node ?? "unknown"),
  platform: String(report.platform ?? "unknown"),
  arch: String(report.arch ?? "unknown"),
  iterations: finite(report.iterations, "iterations"),
  warmups: finite(report.warmups, "warmups"),
  workloads: report.workloads.map((workload) => ({
    workload: String(workload.workload),
    outputBytes: finite(workload.outputBytes, `${workload.workload}.outputBytes`),
    outputSha256: String(workload.outputSha256),
    nativeCompileMs: finite(workload.nativeCompileMs, `${workload.workload}.nativeCompileMs`),
    interpreterMedianMs: finite(workload.interpreterMedianMs, `${workload.workload}.interpreterMedianMs`),
    nativeMedianMs: finite(workload.nativeMedianMs, `${workload.workload}.nativeMedianMs`),
    interpreterToNativeMedianRatio: finite(workload.interpreterToNativeMedianRatio, `${workload.workload}.ratio`),
  })),
};

writeFileSync(
  outputPath,
  `// Generated by scripts/benchmark-page.mjs. Do not edit by hand.\n` +
    `globalThis.OSTRIN_BENCHMARK = Object.freeze(${JSON.stringify(data, null, 2)});\n`,
  "utf8",
);
console.log(`benchmark-page: wrote ${path.relative(repositoryRoot, outputPath)}`);
